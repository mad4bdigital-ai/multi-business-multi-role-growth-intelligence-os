import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";

const ROOT = process.cwd();
const ROUTES_DIR = path.join(ROOT, "routes");
const OPENAPI_PATH = path.join(ROOT, "openapi.yaml");
const ALLOWLIST_PATH = path.join(ROOT, "openapi-route-coverage.allowlist.json");
const HTTP_METHODS = new Set(["get", "post", "put", "patch", "delete"]);
const ROUTE_FILE_RE = /(?:router|app)\.(get|post|put|patch|delete)\s*\(\s*([`'\"])(.*?)\2/gs;
const APP_USE_RE = /app\.use\s*\(\s*([`'\"])(.*?)\1\s*,/gs;
const ROUTER_USE_RE = /router\.use\s*\(\s*([`'\"])(.*?)\1\s*,\s*([A-Za-z0-9_$]+)/gs;

function loadJson(filePath, fallback) {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function normalizeExpressPath(routePath) {
  let p = String(routePath || "").trim();
  if (!p || p === "/") return "/";
  if (!p.startsWith("/")) p = `/${p}`;
  return p.replace(/:([A-Za-z0-9_]+)/g, "{$1}").replace(/\/+/g, "/").replace(/\/$/, "") || "/";
}

function joinPaths(base, routePath) {
  const b = normalizeExpressPath(base || "/");
  const r = normalizeExpressPath(routePath || "/");
  if (b === "/") return r;
  if (r === "/") return b;
  return `${b}${r}`.replace(/\/+/g, "/");
}

function routeFilePaths() {
  return fs.readdirSync(ROUTES_DIR)
    .filter((name) => name.endsWith(".js"))
    .map((name) => path.join(ROUTES_DIR, name))
    .sort();
}

function collectMountPrefixes(indexSource) {
  const prefixes = new Set([""]);
  let match;
  while ((match = APP_USE_RE.exec(indexSource)) !== null) prefixes.add(normalizeExpressPath(match[2]));
  return prefixes;
}

function collectRoutesFromSource(filePath, source, indexPrefixes) {
  const rel = path.relative(ROOT, filePath).replace(/\\/g, "/");
  const localPrefixes = new Set([""]);
  let match;
  while ((match = ROUTER_USE_RE.exec(source)) !== null) {
    const handlerName = String(match[3] || "");
    if (/(Router|Routes)$/i.test(handlerName)) localPrefixes.add(normalizeExpressPath(match[2]));
  }

  const routes = [];
  while ((match = ROUTE_FILE_RE.exec(source)) !== null) {
    const method = match[1].toUpperCase();
    const routePath = normalizeExpressPath(match[3]);
    const prefixes = rel === "routes/index.js" ? indexPrefixes : localPrefixes;
    for (const prefix of prefixes) routes.push({ method, path: joinPaths(prefix, routePath), file: rel });
  }
  return routes;
}

function collectRoutes(requiredFiles = null) {
  const indexPath = path.join(ROUTES_DIR, "index.js");
  const indexSource = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, "utf8") : "";
  const indexPrefixes = collectMountPrefixes(indexSource);
  const required = Array.isArray(requiredFiles) && requiredFiles.length > 0
    ? new Set(requiredFiles.map((p) => p.replace(/\\/g, "/")))
    : null;
  return routeFilePaths()
    .filter((filePath) => {
      if (!required) return true;
      const rel = path.relative(ROOT, filePath).replace(/\\/g, "/");
      return required.has(rel);
    })
    .flatMap((filePath) => collectRoutesFromSource(filePath, fs.readFileSync(filePath, "utf8"), indexPrefixes));
}

function allowlistMatchers(allowlist) {
  const exact = new Set(allowlist.exact || []);
  const prefixes = allowlist.prefixes || [];
  const files = allowlist.files || [];
  return function isAllowed(route) {
    const sig = `${route.method} ${route.path}`;
    if (exact.has(sig)) return true;
    if (prefixes.some((p) => route.path === p || route.path.startsWith(`${p}/`))) return true;
    if (files.includes(route.file)) return true;
    return false;
  };
}

function collectOpenApiOperations(doc) {
  const ops = new Set();
  for (const [pathKey, pathItem] of Object.entries(doc.paths || {})) {
    for (const method of Object.keys(pathItem || {})) {
      if (HTTP_METHODS.has(method)) ops.add(`${method.toUpperCase()} ${pathKey}`);
    }
  }
  return ops;
}

function lowerMethod(method) { return String(method || "").toLowerCase(); }
function pascal(value) {
  return String(value || "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("") || "Route";
}
function operationIdFor(route) {
  const method = lowerMethod(route.method);
  const cleaned = route.path.replace(/[{}]/g, "").replace(/^\//, "");
  return `${method}${pascal(cleaned)}`;
}
function tagFor(route) {
  const first = String(route.path || "/").split("/").filter(Boolean)[0] || "root";
  return first.replace(/[{}]/g, "") || "autogenerated";
}
function statusForSuccess(method) {
  return method === "POST" ? "200" : method === "DELETE" ? "204" : "200";
}
function consequentialFor(method) { return !["GET", "HEAD", "OPTIONS"].includes(String(method || "").toUpperCase()); }

function requestBodyFor(route) {
  if (["GET", "DELETE"].includes(route.method)) return undefined;
  return {
    required: false,
    content: {
      "application/json": {
        schema: {
          type: "object",
          additionalProperties: true,
        },
      },
    },
  };
}

function parametersFor(route) {
  const params = [...String(route.path).matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
  return params.map((name) => ({
    name,
    in: "path",
    required: true,
    schema: { type: "string" },
  }));
}

function responseObject(method) {
  const success = statusForSuccess(method);
  const responses = {
    [success]: success === "204"
      ? { description: "Successful response with no content" }
      : {
          description: "Successful response",
          content: {
            "application/json": {
              schema: { type: "object", additionalProperties: true },
            },
          },
        },
    "400": {
      description: "Invalid request",
      content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorResponse" } } },
    },
    "401": {
      description: "Authentication required",
      content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorResponse" } } },
    },
    "403": {
      description: "Authorization denied",
      content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorResponse" } } },
    },
    "500": {
      description: "Unexpected server failure",
      content: { "application/json": { schema: { $ref: "#/components/schemas/ErrorResponse" } } },
    },
  };
  return responses;
}

function buildStub(route) {
  const method = lowerMethod(route.method);
  const stub = {
    tags: [tagFor(route)],
    operationId: operationIdFor(route),
    summary: `TODO document ${route.method} ${route.path}`,
    description: `Autogenerated OpenAPI stub for ${route.method} ${route.path} from ${route.file}. Replace this description, request schema, response schema, auth notes, and examples with the precise API contract before relying on this route from external clients.`,
    "x-openai-isConsequential": consequentialFor(route.method),
  };
  const parameters = parametersFor(route);
  if (parameters.length) stub.parameters = parameters;
  const requestBody = requestBodyFor(route);
  if (requestBody) stub.requestBody = requestBody;
  stub.responses = responseObject(route.method);
  return { method, stub };
}

function findMissing(doc, allowlist) {
  const openapiOps = collectOpenApiOperations(doc);
  const routes = collectRoutes(allowlist.required_files);
  const isAllowed = allowlistMatchers(allowlist);
  const missing = [];
  const seen = new Set();
  for (const route of routes) {
    const sig = `${route.method} ${route.path}`;
    if (seen.has(`${sig} ${route.file}`)) continue;
    seen.add(`${sig} ${route.file}`);
    if (openapiOps.has(sig) || isAllowed(route)) continue;
    missing.push({ ...route, signature: sig });
  }
  return missing;
}

function main() {
  const write = process.argv.includes("--write");
  const failOnMissing = process.argv.includes("--check");
  const doc = YAML.parse(fs.readFileSync(OPENAPI_PATH, "utf8"));
  const allowlist = loadJson(ALLOWLIST_PATH, { exact: [], prefixes: [], files: [], required_files: [] });
  const missing = findMissing(doc, allowlist);

  if (!write) {
    const result = { ok: missing.length === 0, missing_count: missing.length, missing };
    console.log(JSON.stringify(result, null, 2));
    if (failOnMissing && missing.length > 0) process.exit(1);
    return;
  }

  doc.paths ||= {};
  for (const route of missing) {
    doc.paths[route.path] ||= {};
    const { method, stub } = buildStub(route);
    if (!doc.paths[route.path][method]) doc.paths[route.path][method] = stub;
  }

  if (missing.length > 0) {
    const serialized = YAML.stringify(doc, {
      lineWidth: 120,
      aliasDuplicateObjects: false,
      sortKeys: false,
      quotingType: '"',
    });
    fs.writeFileSync(OPENAPI_PATH, `${serialized.trimEnd()}\n`);
  }

  console.log(JSON.stringify({ ok: true, changed: missing.length > 0, missing_count: missing.length, missing }, null, 2));
}

main();
