#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";

const API_ROOT = process.cwd();
const REPO_ROOT = path.resolve(API_ROOT, "..");
const OPENAPI_PATH = path.join(API_ROOT, "openapi.yaml");
const ALLOWLIST_PATH = path.join(API_ROOT, "openapi-route-coverage.allowlist.json");
const OUTPUT_PATH = path.join(REPO_ROOT, "docs", "repo-maintenance-status.md");
const WORKFLOWS_DIR = path.join(REPO_ROOT, ".github", "workflows");

function loadJson(filePath, fallback) {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function listFiles(dir, predicate = () => true) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(predicate).sort();
}

function countOpenApiOperations(doc) {
  const methods = new Set(["get", "post", "put", "patch", "delete"]);
  let count = 0;
  for (const pathItem of Object.values(doc.paths || {})) {
    for (const method of Object.keys(pathItem || {})) if (methods.has(method)) count += 1;
  }
  return count;
}

function topTags(doc) {
  const counts = new Map();
  const methods = new Set(["get", "post", "put", "patch", "delete"]);
  for (const pathItem of Object.values(doc.paths || {})) {
    for (const [method, op] of Object.entries(pathItem || {})) {
      if (!methods.has(method)) continue;
      for (const tag of op.tags || ["untagged"]) counts.set(tag, (counts.get(tag) || 0) + 1);
    }
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 20);
}

function markdownList(items) {
  return items.length ? items.map((item) => `- ${item}`).join("\n") : "- none";
}

function main() {
  const doc = YAML.parse(fs.readFileSync(OPENAPI_PATH, "utf8"));
  const allowlist = loadJson(ALLOWLIST_PATH, { exact: [], prefixes: [], files: [], required_files: [] });
  const splitSchemas = listFiles(API_ROOT, (name) => /^openapi\..*\.ya?ml$/.test(name) && name !== "openapi.yaml");
  const workflows = listFiles(WORKFLOWS_DIR, (name) => name.endsWith(".yml") || name.endsWith(".yaml"));
  const keyScripts = listFiles(path.join(API_ROOT, "scripts"), (name) => /openapi|repo-maintenance|schema-docs|surface-contract|split/.test(name));
  const keyTests = listFiles(API_ROOT, (name) => /^test-.*(openapi|platform-plugin|schema).*\.mjs$/.test(name));

  const content = `# Repository Maintenance Status

> Generated by \`http-generic-api/scripts/update-repo-planning-docs.mjs\`. Do not hand-edit generated facts in this file; update the source scripts, workflows, schemas, or tests instead.

## Generation Mode

Deterministic repository-state snapshot. Runtime timestamps are intentionally omitted to avoid automated PR churn.

## OpenAPI Source

- Source file: \`http-generic-api/openapi.yaml\`
- OpenAPI version: \`${doc.openapi || "unknown"}\`
- Paths: ${Object.keys(doc.paths || {}).length}
- Operations: ${countOpenApiOperations(doc)}
- Top-level tags: ${(doc.tags || []).length}

## Top Operation Tags

${topTags(doc).map(([tag, count]) => `- \`${tag}\`: ${count}`).join("\n") || "- none"}

## Generated / Scoped OpenAPI Schemas

${markdownList(splitSchemas.map((name) => `\`http-generic-api/${name}\``))}

## Route Coverage Allowlist

- Required files: ${(allowlist.required_files || []).length}
- Exact allowlist entries: ${(allowlist.exact || []).length}
- Prefix allowlist entries: ${(allowlist.prefixes || []).length}
- File allowlist entries: ${(allowlist.files || []).length}

## Automation Workflows

${markdownList(workflows.map((name) => `\`.github/workflows/${name}\``))}

## Maintenance Scripts

${markdownList(keyScripts.map((name) => `\`http-generic-api/scripts/${name}\``))}

## Schema / Plugin / OpenAPI Tests

${markdownList(keyTests.slice(0, 80).map((name) => `\`http-generic-api/${name}\``))}${keyTests.length > 80 ? `\n- ...and ${keyTests.length - 80} more` : ""}

## Maintenance Contract

- New public routes should be documented in \`http-generic-api/openapi.yaml\`.
- Generated split schemas should derive from the main OpenAPI source.
- DB tool registry rows should preserve method/path/tag parity with OpenAPI when a tool maps to an HTTP route.
- Runtime/schema authority changes should include tests, docs, or canonical coverage.
- Automation should open reviewable PRs rather than pushing generated contract changes directly to \`main\`.
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, content);
  console.log(JSON.stringify({ ok: true, output: path.relative(REPO_ROOT, OUTPUT_PATH), deterministic: true }, null, 2));
}

main();
