#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_REPO_ROOT = path.resolve(HERE, "../..");
const DEFAULT_OUT_DIR = "docs/work-maps";

function readText(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
}

function listFiles(dir, predicate = () => true) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listFiles(full, predicate);
      return predicate(full) ? [full] : [];
    })
    .sort();
}

function rel(repoRoot, file) {
  return path.relative(repoRoot, file).replaceAll("\\", "/");
}

function hashFiles(repoRoot, files) {
  const h = crypto.createHash("sha256");
  for (const file of [...new Set(files)].sort()) {
    h.update(rel(repoRoot, file));
    h.update("\0");
    h.update(readText(file));
    h.update("\0");
  }
  return h.digest("hex");
}

function esc(value = "") {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ").trim();
}

function mermaidId(value = "") {
  return `n_${String(value).replace(/[^A-Za-z0-9_]/g, "_")}`;
}

function uniq(values) {
  return [...new Set(values.filter(Boolean))].sort();
}

function groupExecutionArg(name) {
  if (/^(tenant|workspace|user|actor|role|policy)/i.test(name)) return "Identity & authorization";
  if (/^(brand|activity|business|knowledgeProfile)/i.test(name)) return "Brand & business context";
  if (/^(connectedSystem|installation|permission|connector|provider|resourceAuthority|budgetAuthority)/i.test(name)) return "Connection & authority";
  if (/^(engine|model|logic)/i.test(name)) return "Intelligence runtime";
  if (/^(agent|skill|app|plugin|workflow|action|tool|parentAction|endpoint)/i.test(name)) return "Execution surfaces";
  if (/Evidence$/i.test(name)) return "Evidence envelopes";
  return "Trace & delivery";
}

function parseExecutionEvidence(repoRoot) {
  const loggerFile = path.join(repoRoot, "http-generic-api/executionEvidenceLogger.js");
  const migrationDir = path.join(repoRoot, "http-generic-api/migrations");
  const logger = readText(loggerFile);
  const signature = logger.match(/export\s+async\s+function\s+writeExecutionEvidence\s*\(\s*\{([\s\S]*?)\}\s*=\s*\{\}\s*\)/)?.[1] || "";
  const args = uniq([...signature.matchAll(/^\s*([A-Za-z_$][\w$]*)\s*(?:=|,)/gm)].map((m) => m[1]));
  const migrationFiles = listFiles(migrationDir, (file) => file.endsWith(".sql") && /execution_log/i.test(readText(file)));
  const migrationText = migrationFiles.map(readText).join("\n");
  const columns = uniq([...migrationText.matchAll(/ADD\s+COLUMN\s+IF\s+NOT\s+EXISTS\s+`([^`]+)`/gi)].map((m) => m[1]));
  const evidenceColumns = columns.filter((name) => /_evidence_json$/.test(name));
  const views = uniq([...migrationText.matchAll(/CREATE\s+OR\s+REPLACE\s+VIEW\s+`(v_execution_log_[^`]+)`/gi)].map((m) => m[1]));
  const policies = uniq([...migrationText.matchAll(/'(execution_log_[a-z0-9_]+policy_v\d+)'/gi)].map((m) => m[1]));
  return { loggerFile, migrationFiles, args, columns, evidenceColumns, views, policies };
}

function parseActivationSurfaces(repoRoot) {
  const dir = path.join(repoRoot, "http-generic-api/activation-surfaces");
  const files = listFiles(dir, (file) => file.endsWith(".json") && !file.includes(`${path.sep}exclusions${path.sep}`));
  const surfaces = files.map((file) => {
    try {
      const data = JSON.parse(readText(file));
      return {
        file,
        key: data.surface_key || path.basename(file, ".json"),
        source: data.source_table || "",
        admin: data.include_for_admin === true,
        tenant: data.include_for_tenant === true,
        status: data.status || "unknown",
        columns: Array.isArray(data.result_columns) ? data.result_columns : [],
      };
    } catch {
      return null;
    }
  }).filter(Boolean).sort((a, b) => a.key.localeCompare(b.key));
  return { files, surfaces };
}

function parseWorkflows(repoRoot) {
  const dir = path.join(repoRoot, ".github/workflows");
  const files = listFiles(dir, (file) => /\.ya?ml$/i.test(file));
  const workflows = files.map((file) => {
    const text = readText(file);
    const name = text.match(/^name:\s*(.+)$/m)?.[1]?.trim() || path.basename(file);
    const triggers = [];
    for (const trigger of ["workflow_dispatch", "pull_request", "push", "schedule", "workflow_run"]) {
      if (new RegExp(`^\\s*${trigger}:`, "m").test(text)) triggers.push(trigger);
    }
    return { file, name, triggers };
  });
  return { files, workflows };
}

function sourceHeader(hash, sources) {
  return [
    "> Generated text documentation. Do not edit this file manually.",
    `> Source hash: \`${hash}\``,
    `> Sources: ${sources.map((s) => `\`${s}\``).join(", ")}`,
    "> Rendering: Mermaid code blocks plus Markdown tables; no image assets are generated.",
    "",
  ].join("\n");
}

function renderExecutionMap(repoRoot, data) {
  const sourceFiles = [data.loggerFile, ...data.migrationFiles];
  const hash = hashFiles(repoRoot, sourceFiles);
  const grouped = new Map();
  for (const arg of data.args) {
    const group = groupExecutionArg(arg);
    if (!grouped.has(group)) grouped.set(group, []);
    grouped.get(group).push(arg);
  }
  const tableRows = [...grouped.entries()].sort().map(([group, args]) => `| ${esc(group)} | ${args.map((v) => `\`${v}\``).join(", ")} |`).join("\n");
  const evidenceRows = data.evidenceColumns.map((name) => `| \`${name}\` | JSON evidence envelope |`).join("\n");
  const viewRows = data.views.map((name) => `| \`${name}\` | Readback/readiness |`).join("\n");
  return `# Execution Log Evidence Map\n\n${sourceHeader(hash, sourceFiles.map((f) => rel(repoRoot, f)))}\n\n\`\`\`mermaid\nflowchart LR\n  Request[Request / Trigger] --> Router[prompt_router]\n  Router --> Loader[module_loader]\n  Loader --> Bootstrap[system_bootstrap]\n  Bootstrap --> Governance[Governance & policy validation]\n  Governance --> Runtime[Agent / Skill / App / Workflow runtime]\n  Runtime --> Context[Brand + Activity + Authority + Intelligence context]\n  Context --> Logger[writeExecutionEvidence]\n  Logger --> Ledger[(execution_log)]\n  Ledger --> Recent[v_execution_log_*_recent]\n  Ledger --> Readiness[v_execution_log_*_readiness]\n  Readiness --> Audit[Release / operational evidence]\n\`\`\`\n\n## Discovered logger inputs\n\n| Context group | Inputs |\n|---|---|\n${tableRows}\n\n## Discovered evidence columns\n\n| Column | Purpose |\n|---|---|\n${evidenceRows || "| _none discovered_ | - |"}\n\n## Readback surfaces\n\n| View | Role |\n|---|---|\n${viewRows || "| _none discovered_ | - |"}\n\n## Governing policies\n\n${data.policies.length ? data.policies.map((p) => `- \`${p}\``).join("\n") : "- No execution-log policy key was discovered."}\n\n## Coverage counters\n\n- Logger inputs discovered: **${data.args.length}**\n- Execution-log columns discovered from migrations: **${data.columns.length}**\n- Evidence JSON columns: **${data.evidenceColumns.length}**\n- Readback views: **${data.views.length}**\n`;
}

function renderActivationMap(repoRoot, data) {
  const hash = hashFiles(repoRoot, data.files);
  const nodes = data.surfaces.map((surface) => {
    const scope = surface.admin && surface.tenant ? "admin + tenant" : surface.admin ? "admin" : surface.tenant ? "tenant" : "disabled";
    return `  ${mermaidId(surface.key)}["${surface.key}<br/>${scope}"]`;
  }).join("\n");
  const edges = data.surfaces.map((surface) => `  Registry --> ${mermaidId(surface.key)}`).join("\n");
  const rows = data.surfaces.map((surface) => `| \`${surface.key}\` | \`${surface.source}\` | ${surface.admin ? "yes" : "no"} | ${surface.tenant ? "yes" : "no"} | ${surface.status} | ${surface.columns.length} |`).join("\n");
  return `# Activation and Authorized Access Map\n\n${sourceHeader(hash, data.files.map((f) => rel(repoRoot, f)))}\n\n\`\`\`mermaid\nflowchart TD\n  Session[Activation session context] --> Authorization[Dynamic authorization envelope]\n  Authorization --> Registry[Activation surface registry]\n${nodes}\n${edges}\n  Registry --> SafeFilter[Sensitive-field filter]\n  SafeFilter --> Admin[Admin authorized access]\n  SafeFilter --> Tenant[Tenant-scoped authorized access]\n\`\`\`\n\n## Registered surfaces\n\n| Surface | Source table/view | Admin | Tenant | Status | Result columns |\n|---|---|---:|---:|---|---:|\n${rows}\n\nTotal generated surfaces: **${data.surfaces.length}**.\n`;
}

function renderAutomationMap(repoRoot, data) {
  const hash = hashFiles(repoRoot, data.files);
  const nodes = data.workflows.map((workflow) => `  ${mermaidId(workflow.name)}["${workflow.name}"]`).join("\n");
  const edges = data.workflows.map((workflow) => `  Change --> ${mermaidId(workflow.name)}`).join("\n");
  const rows = data.workflows.map((workflow) => `| ${esc(workflow.name)} | \`${rel(repoRoot, workflow.file)}\` | ${workflow.triggers.map((t) => `\`${t}\``).join(", ") || "manual/other"} |`).join("\n");
  return `# Repository Automation Map\n\n${sourceHeader(hash, data.files.map((f) => rel(repoRoot, f)))}\n\n\`\`\`mermaid\nflowchart TD\n  Change[Repository change] --> PR[Pull request]\n${nodes}\n${edges}\n  PR --> CI[CI validation]\n  PR --> Docs[Docs Agent]\n  Docs --> Maps[Regenerate text work maps]\n  Maps --> Review[Reviewable Markdown diff]\n  CI --> Merge[Governed merge]\n  Review --> Merge\n\`\`\`\n\n## Workflow inventory\n\n| Workflow | File | Detected triggers |\n|---|---|---|\n${rows}\n\nWorkflow files discovered: **${data.workflows.length}**.\n`;
}

function renderRuntimeMap(repoRoot) {
  const sourceRel = [
    "prompt_router.md",
    "module_loader.md",
    "system_bootstrap.md",
    "http-generic-api/executionEvidenceLogger.js",
    "http-generic-api/connectorExecutor.js",
    "http-generic-api/agentRuntime.js",
  ];
  const sources = sourceRel.map((p) => path.join(repoRoot, p)).filter(fs.existsSync);
  const hash = hashFiles(repoRoot, sources);
  return `# Platform Runtime Work Map\n\n${sourceHeader(hash, sources.map((f) => rel(repoRoot, f)))}\n\n\`\`\`mermaid\nflowchart TD\n  Input[User / system intent] --> Router[prompt_router]\n  Router --> Activity[Business activity resolution]\n  Activity --> Brand[Brand Core readiness]\n  Brand --> Loader[module_loader]\n  Loader --> Bootstrap[system_bootstrap]\n  Bootstrap --> Bindings[Route + workflow + dependency bindings]\n  Bindings --> Authorization[Credential + permission + authority resolution]\n  Authorization --> AgentLoop[runAgentLoop -> getAgentDeps]\n  AgentLoop --> Logic[Logic / engine / model selection]\n  Logic --> Connector[connectorExecutor]\n  Connector --> Provider[Governed provider transport]\n  Provider --> Result[Normalized result]\n  Result --> Evidence[writeExecutionEvidence]\n  Evidence --> Ledger[(execution_log)]\n  Ledger --> Memory[Memory / writeback / operational readback]\n\`\`\`\n\n## Runtime invariants\n\n- Provider calls are routed through governed connector transport.\n- Brand writing requires resolved Brand Core evidence.\n- Business activity type is resolved before knowledge and engine compatibility.\n- Agent workflows use \`runAgentLoop -> getAgentDeps()\`.\n- Execution evidence records identity, authorization, business context, runtime surfaces, and intelligence attribution.\n- Secret values and sensitive payload fields are excluded from generated documentation and execution evidence.\n`;
}

function renderIndex(repoRoot, maps, sourceFiles) {
  const hash = hashFiles(repoRoot, sourceFiles);
  return `# Dynamic Platform Work Maps\n\n${sourceHeader(hash, sourceFiles.map((f) => rel(repoRoot, f)))}\n\nThese documents are generated from repository source and updated by Docs Agent and repository maintenance synchronization. They are text-only and render as Mermaid diagrams where supported. Raw Markdown remains readable without Mermaid rendering.\n\n## Maps\n\n${Object.keys(maps).filter((name) => name !== "README.md").sort().map((name) => `- [${name.replace(/\.md$/, "").replaceAll("-", " ")}](./${name})`).join("\n")}\n\n## Update contract\n\n1. Platform source, manifests, migrations, or workflows change.\n2. \`platform-work-map-generator.mjs --write\` regenerates the Markdown files.\n3. Docs Agent commits the generated diff to the PR branch.\n4. CI checks the generator contract and normal repository tests.\n5. Reviewers inspect the text diff before merge.\n\nNo image files, credentials, provider payloads, runtime secrets, or raw database rows are generated.\n`;
}

export function buildWorkMaps({ repoRoot = DEFAULT_REPO_ROOT } = {}) {
  const execution = parseExecutionEvidence(repoRoot);
  const activation = parseActivationSurfaces(repoRoot);
  const workflows = parseWorkflows(repoRoot);
  const maps = {
    "execution-log-evidence-map.md": renderExecutionMap(repoRoot, execution),
    "activation-access-map.md": renderActivationMap(repoRoot, activation),
    "repository-automation-map.md": renderAutomationMap(repoRoot, workflows),
    "platform-runtime-map.md": renderRuntimeMap(repoRoot),
  };
  const allSources = uniq([
    execution.loggerFile,
    ...execution.migrationFiles,
    ...activation.files,
    ...workflows.files,
    ...["prompt_router.md", "module_loader.md", "system_bootstrap.md"].map((p) => path.join(repoRoot, p)).filter(fs.existsSync),
  ]);
  maps["README.md"] = renderIndex(repoRoot, maps, allSources);
  return { maps, sourceFiles: allSources };
}

export function syncWorkMaps({ repoRoot = DEFAULT_REPO_ROOT, outDir = DEFAULT_OUT_DIR, mode = "write" } = {}) {
  const { maps, sourceFiles } = buildWorkMaps({ repoRoot });
  const absoluteOut = path.resolve(repoRoot, outDir);
  const drift = [];
  for (const [name, content] of Object.entries(maps)) {
    const file = path.join(absoluteOut, name);
    const current = readText(file);
    if (current !== content) drift.push(rel(repoRoot, file));
    if (mode === "write") {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content);
    }
  }
  const result = {
    ok: mode === "write" || drift.length === 0,
    mode,
    output_dir: outDir,
    generated_files: Object.keys(maps).sort(),
    generated_count: Object.keys(maps).length,
    source_count: sourceFiles.length,
    drift_files: drift,
    secrets_included: false,
    image_assets_generated: false,
  };
  return result;
}

function parseArgs(argv = process.argv.slice(2)) {
  return {
    mode: argv.includes("--check") ? "check" : "write",
    outDir: argv.find((arg) => arg.startsWith("--out-dir="))?.slice("--out-dir=".length) || DEFAULT_OUT_DIR,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = parseArgs();
  const result = syncWorkMaps({ outDir: args.outDir, mode: args.mode });
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  if (!result.ok) process.exit(1);
}
