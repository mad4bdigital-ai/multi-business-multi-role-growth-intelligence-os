-- Sprint 64: OpenClaude provider registry and runtime provider profiles.
-- Catalogs OpenClaude-native providers and platform-governed bridge options.
-- Stores no credentials and exposes no secret values.

CREATE TABLE IF NOT EXISTS dev_agent_provider_registry (
  provider_key VARCHAR(191) NOT NULL PRIMARY KEY,
  display_name VARCHAR(255) NOT NULL,
  provider_family VARCHAR(64) NOT NULL DEFAULT 'openclaude_native',
  openclaude_provider_key VARCHAR(64) NULL,
  credential_mode ENUM('local_env','platform_managed','local_service','external_cloud','none') NOT NULL DEFAULT 'none',
  execution_surface ENUM('local_device','platform_control_plane','external_cloud') NOT NULL DEFAULT 'local_device',
  supported_runtime_types_json JSON NULL,
  required_env_names_json JSON NULL,
  capabilities_json JSON NULL,
  policy_json JSON NULL,
  status ENUM('planned','available','active','degraded','disabled') NOT NULL DEFAULT 'planned',
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_dev_agent_provider_registry_status (status, provider_family, credential_mode),
  KEY idx_dev_agent_provider_registry_openclaude (openclaude_provider_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS dev_agent_runtime_provider_profiles (
  profile_key VARCHAR(191) NOT NULL PRIMARY KEY,
  runtime_key VARCHAR(191) NOT NULL,
  provider_key VARCHAR(191) NOT NULL,
  profile_name VARCHAR(255) NOT NULL,
  selection_mode ENUM('manual','fallback','preferred','disabled') NOT NULL DEFAULT 'manual',
  credential_mode ENUM('local_env','platform_managed','local_service','external_cloud','none') NOT NULL DEFAULT 'none',
  model_hint VARCHAR(191) NULL,
  endpoint_url VARCHAR(500) NULL,
  status ENUM('planned','available','active','degraded','disabled') NOT NULL DEFAULT 'planned',
  policy_json JSON NULL,
  metadata_json JSON NULL,
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_dev_agent_runtime_provider_profiles_runtime (runtime_key, status),
  KEY idx_dev_agent_runtime_provider_profiles_provider (provider_key, status),
  KEY idx_dev_agent_runtime_provider_profiles_selection (selection_mode, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

