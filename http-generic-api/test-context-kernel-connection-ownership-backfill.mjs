import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const sql = fs.readFileSync(path.join(here,'migrations','20260808_context_kernel_connection_ownership_backfill.sql'),'utf8');
assert.match(sql,/UPDATE `workspace_registry` AS `wr`/);
assert.match(sql,/proposed_ownership_type` IN \('personal','company'\)/);
