assert.match(sql,/WHERE NOT EXISTS \(/);
assert.match(sql,/'personal_workspace'/);
assert.match(sql,/'company_workspace'/);
assert.match(sql,/'unclassified'/);
const insert = sql.slice(sql.indexOf('INSERT INTO `connection_ownership_scopes`'));
assert.match(insert,/`legacy_connection`\.`app_key`, NULL, NULL, NULL, 1, 1, 'unclassified'/);
assert.doesNotMatch(insert,/email_key/i);
assert.doesNotMatch(insert,/account_metadata/i);
assert.doesNotMatch(insert,/encrypted_credentials/i);
assert.doesNotMatch(insert,/SHA2\s*\(/i);
assert.doesNotMatch(sql,/\bDELETE\b/i);
assert.doesNotMatch(sql,/\bTRUNCATE\b/i);
assert.doesNotMatch(sql,/\bDROP\b/i);
console.log('context-kernel connection ownership backfill migration contract: ok');
