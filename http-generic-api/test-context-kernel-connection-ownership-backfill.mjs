assert.match(sql,/resource_ref` = BINARY `grant_workspace`\.`workspace_id`[\s\S]*resource_ref` = BINARY `grant_workspace`\.`tenant_id`/);
assert.match(sql,/INSERT INTO `connection_ownership_scopes`/);
