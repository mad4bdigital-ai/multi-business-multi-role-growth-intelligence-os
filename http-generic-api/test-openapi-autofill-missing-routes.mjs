import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const script = readFileSync('scripts/openapi-autofill-missing-routes.mjs', 'utf8');
const preciseSync = readFileSync('scripts/openapi-precise-contract-registry-sync.mjs', 'utf8');
const maintenanceSync = readFileSync('scripts/repo-maintenance-sync.mjs', 'utf8');
const todoGuard = readFileSync('scripts/openapi-forbid-autogenerated-todos.mjs', 'utf8');
const workflow = readFileSync('../.github/workflows/openapi-auto-sync.yml', 'utf8');
const refreshWorkflow = readFileSync('../.github/workflows/pr-generated-artifact-refresh.yml', 'utf8');

assert(workflow.includes('openapi-autofill-missing-routes.mjs') || workflow.includes('repo-maintenance-sync.mjs --write'), 'workflow should call the autofill generator directly or through repo maintenance orchestration');
assert(script.includes('ROUTE_FILE_RE'), 'autofill must parse express route declarations');
assert(script.includes('ALLOWLIST_PATH'), 'autofill must honor openapi route coverage allowlist');
assert(script.includes('CONTRACT_REGISTRY_PATH'), 'autofill must support precise route contracts discovered with runtime routes');
assert(script.includes('route_file'), 'precise route contracts must bind to a runtime route source');
assert(script.includes('operationIdFor'), 'autofill must create stable operationIds');
assert(script.includes('x-openai-isConsequential'), 'autofill must mark consequential operations');
assert(script.includes('TODO document'), 'autofill stubs must be clearly review-required');
assert(script.includes('#/components/schemas/ErrorResponse'), 'autofill stubs must use shared structured error schema');
assert(script.includes('process.argv.includes("--write")'), 'autofill must require --write for mutation');
assert(script.includes('process.argv.includes("--check")'), 'autofill must support check mode');

assert(preciseSync.includes('openapi_precise_contract_path_conflict'), 'precise registry sync must fail closed on occupied or mismatched root paths');
assert(preciseSync.includes('path_item_ref'), 'precise registry sync must project registered path-item references');
assert(preciseSync.includes('process.argv.includes("--write")'), 'precise registry sync must require explicit write mode');
assert(preciseSync.includes('process.argv.includes("--check")'), 'precise registry sync must support fail-closed check mode');
assert(maintenanceSync.indexOf('openapi-precise-contract-registry-sync.mjs') < maintenanceSync.indexOf('openapi-autofill-missing-routes.mjs'), 'maintenance sync must apply authoritative precise contracts before route-derived autofill');
assert(refreshWorkflow.includes('node scripts/openapi-precise-contract-registry-sync.mjs --write'), 'PR artifact refresh must compose precise registry contracts before generic autofill');
assert(refreshWorkflow.includes('node test-openapi-autofill-missing-routes.mjs'), 'PR artifact refresh must execute the precise-registry regression before commit');

assert(todoGuard.includes('openapi_autogenerated_todo_stubs_forbidden'), 'TODO guard must fail with a stable structured error code');
assert(todoGuard.includes('Autogenerated OpenAPI TODO stubs must be reviewed'), 'TODO guard must explain review requirement');

assert(workflow.includes('name: OpenAPI Auto Sync'), 'workflow must exist');
assert(workflow.includes('branches:\n      - main'), 'workflow must run on pushes to main');
assert(workflow.includes('workflow_dispatch'), 'workflow must support manual dispatch');
assert(workflow.includes('node scripts/openapi-autofill-missing-routes.mjs --write') || workflow.includes('node scripts/repo-maintenance-sync.mjs --write'), 'workflow must run autofill generator directly or through the repository maintenance orchestrator');
assert(workflow.includes('peter-evans/create-pull-request@v6'), 'workflow must create a PR instead of pushing directly to main');
assert(workflow.includes('Do not merge this PR as-is'), 'workflow PR body must require human/GPT review of generated stubs');
assert(!workflow.includes('git push origin main'), 'workflow must not push generated stubs directly to main');

const tempRoot = join(tmpdir(), `openapi-autofill-${process.pid}-${Date.now()}`);
const autofillScriptPath = resolve('scripts/openapi-autofill-missing-routes.mjs');
const preciseSyncPath = resolve('scripts/openapi-precise-contract-registry-sync.mjs');
try {
  mkdirSync(join(tempRoot, 'routes'), { recursive: true });
  mkdirSync(join(tempRoot, 'openapi'), { recursive: true });
  writeFileSync(join(tempRoot, 'routes/index.js'), '');
  writeFileSync(join(tempRoot, 'routes/exampleRoutes.js'), [
    'import express from "express";',
    'const router = express.Router();',
    'router.post("/auto-sync-fixture/:id", (req, res) => res.json({ ok: true }));',
    'export default router;',
    '',
  ].join('\n'));
  writeFileSync(join(tempRoot, 'routes/preciseRoutes.js'), [
    'import express from "express";',
    'const router = express.Router();',
    'router.post("/precise-fixture", (req, res) => res.json({ ok: true }));',
    'export default router;',
    '',
  ].join('\n'));
  writeFileSync(join(tempRoot, 'openapi-route-coverage.allowlist.json'), JSON.stringify({
    exact: [],
    prefixes: [],
    files: [],
    required_files: ['routes/exampleRoutes.js'],
  }, null, 2));
  writeFileSync(join(tempRoot, 'openapi-route-contracts.yaml'), [
    'contracts:',
    '  POST /precise-fixture:',
    "    route_file: 'routes/preciseRoutes.js'",
    "    path_item_ref: './openapi/precise-fixture.yaml#/preciseFixture'",
    '  POST /registry-only-fixture:',
    "    route_file: 'routes/registryOnlyRoutes.js'",
    "    path_item_ref: './openapi/registry-only-fixture.yaml#/registryOnlyFixture'",
    '',
  ].join('\n'));
  writeFileSync(join(tempRoot, 'openapi/precise-fixture.yaml'), 'preciseFixture:\n  post:\n    operationId: createPreciseFixture\n    responses:\n      "200": { description: ok }\n');
  writeFileSync(join(tempRoot, 'openapi/registry-only-fixture.yaml'), 'registryOnlyFixture:\n  post:\n    operationId: createRegistryOnlyFixture\n    responses:\n      "200": { description: ok }\n');
  writeFileSync(join(tempRoot, 'openapi.yaml'), 'openapi: 3.1.0\ninfo:\n  title: Fixture\n  version: 1.0.0\npaths: {}\ncomponents:\n  schemas:\n    ErrorResponse:\n      type: object\n      additionalProperties: true\n');

  const routeCheckOutput = execFileSync(process.execPath, [autofillScriptPath], { cwd: tempRoot, encoding: 'utf8' });
  const routeCheckJson = JSON.parse(routeCheckOutput);
  assert.equal(routeCheckJson.ok, false, 'route-derived autofill should report missing runtime routes before write');
  assert.equal(routeCheckJson.missing_count, 2, 'route-derived autofill should detect the allowlisted stub and source-bound precise route');
  assert(routeCheckJson.missing.some((entry) => entry.signature === 'POST /auto-sync-fixture/{id}'));
  assert(routeCheckJson.missing.some((entry) => entry.signature === 'POST /precise-fixture'));
  assert(!routeCheckJson.missing.some((entry) => entry.signature === 'POST /registry-only-fixture'), 'generic route discovery cannot be trusted to discover separately mounted registry-only paths');

  const preciseReportOutput = execFileSync(process.execPath, [preciseSyncPath], { cwd: tempRoot, encoding: 'utf8' });
  const preciseReportJson = JSON.parse(preciseReportOutput);
  assert.equal(preciseReportJson.ok, false, 'precise registry report should expose missing root path refs before write');
  assert.equal(preciseReportJson.missing_count, 2, 'both registered precise contracts must be treated as authoritative even when one is absent from route discovery');

  const preciseWriteOutput = execFileSync(process.execPath, [preciseSyncPath, '--write'], { cwd: tempRoot, encoding: 'utf8' });
  const preciseWriteJson = JSON.parse(preciseWriteOutput);
  assert.equal(preciseWriteJson.changed, true, 'precise registry write must compose missing root path refs');
  assert.equal(preciseWriteJson.applied_precise_contracts.length, 2);
  assert.equal(preciseWriteJson.missing_count, 0);

  const writeOutput = execFileSync(process.execPath, [autofillScriptPath, '--write'], { cwd: tempRoot, encoding: 'utf8' });
  const writeJson = JSON.parse(writeOutput);
  assert.equal(writeJson.changed, true, 'generic autofill should still generate the uncovered stub');
  assert.deepEqual(writeJson.applied_precise_contracts, [], 'precise contracts should already be composed by the authoritative registry sync');
  assert.deepEqual(writeJson.generated_stubs, ['POST /auto-sync-fixture/{id}']);

  const updated = readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8');
  assert(updated.includes('/auto-sync-fixture/{id}:'), 'generated OpenAPI must include normalized path parameter');
  assert(updated.includes('operationId: postAutoSyncFixtureId'), 'generated OpenAPI must include stable operationId');
  assert(updated.includes('TODO document POST /auto-sync-fixture/{id}'), 'generated stub must be review-required');
  assert(updated.includes('x-openai-isConsequential: true'), 'POST route must be consequential');
  assert(updated.includes('/precise-fixture:'), 'runtime-discovered precise route must be inserted');
  assert(updated.includes('$ref: ./openapi/precise-fixture.yaml#/preciseFixture'), 'runtime-discovered precise route must use the registered path-item ref');
  assert(updated.includes('/registry-only-fixture:'), 'registry-only precise route must be inserted independently of route discovery');
  assert(updated.includes('$ref: ./openapi/registry-only-fixture.yaml#/registryOnlyFixture'), 'registry-only route must use the registered path-item ref');

  const preciseFinalOutput = execFileSync(process.execPath, [preciseSyncPath, '--check'], { cwd: tempRoot, encoding: 'utf8' });
  const preciseFinalJson = JSON.parse(preciseFinalOutput);
  assert.equal(preciseFinalJson.ok, true, 'precise registry check must pass after composition');
  assert.equal(preciseFinalJson.missing_count, 0);

  const finalCheckOutput = execFileSync(process.execPath, [autofillScriptPath, '--check'], { cwd: tempRoot, encoding: 'utf8' });
  const finalCheckJson = JSON.parse(finalCheckOutput);
  assert.equal(finalCheckJson.ok, true, 'referenced path items must satisfy subsequent route coverage checks');
  assert.equal(finalCheckJson.missing_count, 0);

  const conflictedRoot = updated.replace(
    '  /registry-only-fixture:\n    $ref: ./openapi/registry-only-fixture.yaml#/registryOnlyFixture',
    '  /registry-only-fixture:\n    post:\n      operationId: conflictingRegistryOnlyFixture\n      responses:\n        "200": { description: conflict }',
  );
  writeFileSync(join(tempRoot, 'openapi.yaml'), conflictedRoot);
  const conflictResult = spawnSync(process.execPath, [preciseSyncPath, '--check'], { cwd: tempRoot, encoding: 'utf8' });
  assert.notEqual(conflictResult.status, 0, 'precise registry sync must fail closed instead of replacing an occupied root path');
  assert.match(conflictResult.stderr, /openapi_precise_contract_path_conflict/);
} finally {
  rmSync(tempRoot, { recursive: true, force: true });
}

console.log('openapi autofill automation tests passed');
