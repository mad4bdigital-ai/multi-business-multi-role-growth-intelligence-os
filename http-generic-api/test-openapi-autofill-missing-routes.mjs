import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const script = readFileSync('scripts/openapi-autofill-missing-routes.mjs', 'utf8');
const preciseSync = readFileSync('scripts/openapi-precise-contract-registry-sync.mjs', 'utf8');
const maintenanceSync = readFileSync('scripts/repo-maintenance-sync.mjs', 'utf8');
const todoGuard = readFileSync('scripts/openapi-forbid-autogenerated-todos.mjs', 'utf8');
const workflow = readFileSync('../.github/workflows/openapi-auto-sync.yml', 'utf8');
const refreshWorkflow = readFileSync('../.github/workflows/pr-generated-artifact-refresh.yml', 'utf8');
const refreshRunner = readFileSync('scripts/generated-artifact-refresh-runner.mjs', 'utf8');

assert(
  workflow.includes('openapi-autofill-missing-routes.mjs')
    || workflow.includes('repo-maintenance-sync.mjs --write'),
  'workflow should call the missing-route coverage gate directly or through repo maintenance orchestration',
);
assert(script.includes('ROUTE_FILE_RE'), 'coverage gate must parse express route declarations');
assert(script.includes('ALLOWLIST_PATH'), 'coverage gate must honor the OpenAPI route coverage allowlist');
assert(script.includes('CONTRACT_REGISTRY_PATH'), 'coverage gate must load precise route contracts');
assert(script.includes('route_file'), 'precise route contracts must bind to a runtime route source');
assert(script.includes('process.argv.includes("--write")'), 'coverage gate must retain --write compatibility for maintenance orchestration');
assert(script.includes('process.argv.includes("--check")'), 'coverage gate must support check mode');
assert(script.includes('missing_precise_contracts'), 'coverage gate must expose a stable fail-closed reason');
assert(script.includes('repository_mutation_performed: false'), 'coverage gate must attest that it never mutates the repository');
assert(!script.includes('function buildStub'), 'coverage gate must not synthesize generic OpenAPI operations');
assert(!script.includes('TODO document'), 'coverage gate must not manufacture review-required TODO contracts');
assert(!script.includes('fs.writeFileSync(OPENAPI_PATH'), 'coverage gate must never rewrite or reserialize the root OpenAPI contract');

assert(
  preciseSync.includes('openapi_precise_contract_path_conflict'),
  'precise registry sync must fail closed on occupied or mismatched root paths',
);
assert(preciseSync.includes('path_item_ref'), 'precise registry sync must project registered path-item references');
assert(preciseSync.includes('process.argv.includes("--write")'), 'precise registry sync must require explicit write mode');
assert(preciseSync.includes('process.argv.includes("--check")'), 'precise registry sync must support fail-closed check mode');
assert(
  maintenanceSync.indexOf('openapi-precise-contract-registry-sync.mjs')
    < maintenanceSync.indexOf('openapi-autofill-missing-routes.mjs'),
  'maintenance sync must apply authoritative precise contracts before the missing-route gate',
);
assert(
  refreshWorkflow.includes('node scripts/generated-artifact-refresh-runner.mjs'),
  'PR artifact refresh must delegate generation and verification to the registered runner',
);
assert(
  refreshRunner.indexOf('openapi-precise-contract-registry-sync.mjs')
    < refreshRunner.indexOf('openapi-autofill-missing-routes.mjs'),
  'PR artifact refresh runner must compose precise registry contracts before checking missing routes',
);
assert(
  refreshRunner.includes('test-openapi-autofill-missing-routes.mjs'),
  'PR artifact refresh runner must execute the fail-closed regression before its decision',
);

assert(todoGuard.includes('openapi_autogenerated_todo_stubs_forbidden'), 'TODO guard must fail with a stable structured error code');
assert(todoGuard.includes('Autogenerated OpenAPI TODO stubs must be reviewed'), 'TODO guard must explain review requirement');

assert(workflow.includes('name: OpenAPI Auto Sync'), 'workflow must exist');
assert(workflow.includes('branches:\n      - main'), 'workflow must run on pushes to main');
assert(workflow.includes('workflow_dispatch'), 'workflow must support manual dispatch');
assert(
  workflow.includes('node scripts/openapi-autofill-missing-routes.mjs --write')
    || workflow.includes('node scripts/repo-maintenance-sync.mjs --write'),
  'workflow must execute the fail-closed gate directly or through repository maintenance',
);
assert(workflow.includes('peter-evans/create-pull-request@v6'), 'workflow must create a PR instead of pushing directly to main');
assert(!workflow.includes('git push origin main'), 'workflow must not push generated contracts directly to main');

const tempRoot = join(tmpdir(), `openapi-autofill-${process.pid}-${Date.now()}`);
const autofillScriptPath = resolve('scripts/openapi-autofill-missing-routes.mjs');
const preciseSyncPath = resolve('scripts/openapi-precise-contract-registry-sync.mjs');

try {
  mkdirSync(join(tempRoot, 'routes'), { recursive: true });
  mkdirSync(join(tempRoot, 'openapi'), { recursive: true });
  writeFileSync(join(tempRoot, 'routes/index.js'), '');
  writeFileSync(join(tempRoot, 'routes/exampleRoutes.js'), [
    'import express from "express";',
    'const router = express.Router();',
    'router.post("/auto-sync-fixture/:id", (req, res) => res.json({ ok: true }));',
    'export default router;',
    '',
  ].join('\n'));
  writeFileSync(join(tempRoot, 'routes/preciseRoutes.js'), [
    'import express from "express";',
    'const router = express.Router();',
    'router.post("/precise-fixture", (req, res) => res.json({ ok: true }));',
    'export default router;',
    '',
  ].join('\n'));
  writeFileSync(join(tempRoot, 'openapi-route-coverage.allowlist.json'), JSON.stringify({
    exact: [],
    prefixes: [],
    files: [],
    required_files: ['routes/exampleRoutes.js'],
  }, null, 2));
  writeFileSync(join(tempRoot, 'openapi-route-contracts.yaml'), [
    'contracts:',
    '  POST /precise-fixture:',
    "    route_file: 'routes/preciseRoutes.js'",
    "    path_item_ref: './openapi/precise-fixture.yaml#/preciseFixture'",
    '  POST /registry-only-fixture:',
    "    route_file: 'routes/registryOnlyRoutes.js'",
    "    path_item_ref: './openapi/registry-only-fixture.yaml#/registryOnlyFixture'",
    '',
  ].join('\n'));
  writeFileSync(
    join(tempRoot, 'openapi/precise-fixture.yaml'),
    'preciseFixture:\n  post:\n    operationId: createPreciseFixture\n    responses:\n      "200": { description: ok }\n',
  );
  writeFileSync(
    join(tempRoot, 'openapi/registry-only-fixture.yaml'),
    'registryOnlyFixture:\n  post:\n    operationId: createRegistryOnlyFixture\n    responses:\n      "200": { description: ok }\n',
  );
  writeFileSync(
    join(tempRoot, 'openapi.yaml'),
    'openapi: 3.1.0\ninfo:\n  title: Fixture\n  version: 1.0.0\npaths: {}\ncomponents:\n  schemas:\n    ErrorResponse:\n      type: object\n      additionalProperties: true\n',
  );

  const initialRoot = readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8');
  const routeReport = JSON.parse(execFileSync(
    process.execPath,
    [autofillScriptPath],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(routeReport.ok, false, 'coverage report should expose missing runtime routes');
  assert.equal(routeReport.changed, false);
  assert.equal(routeReport.repository_mutation_performed, false);
  assert.equal(routeReport.missing_count, 2, 'coverage report should detect the uncovered route and source-bound precise route');
  assert(routeReport.missing.some((entry) => entry.signature === 'POST /auto-sync-fixture/{id}'));
  assert(routeReport.missing.some((entry) => entry.signature === 'POST /precise-fixture'));
  assert(!routeReport.missing.some((entry) => entry.signature === 'POST /registry-only-fixture'));
  assert.equal(readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8'), initialRoot, 'report mode must be byte-identical');

  const preciseReport = JSON.parse(execFileSync(
    process.execPath,
    [preciseSyncPath],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(preciseReport.ok, false, 'precise registry report should expose missing root path refs before write');
  assert.equal(preciseReport.missing_count, 2, 'both registered precise contracts must remain authoritative');

  const preciseWrite = JSON.parse(execFileSync(
    process.execPath,
    [preciseSyncPath, '--write'],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(preciseWrite.changed, true, 'precise registry writer must compose registered root path refs');
  assert.equal(preciseWrite.applied_precise_contracts.length, 2);
  assert.equal(preciseWrite.missing_count, 0);

  const rootAfterPreciseSync = readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8');
  assert(rootAfterPreciseSync.includes('/precise-fixture:'), 'source-bound precise route must be inserted');
  assert(rootAfterPreciseSync.includes('$ref: ./openapi/precise-fixture.yaml#/preciseFixture'));
  assert(rootAfterPreciseSync.includes('/registry-only-fixture:'), 'registry-only precise route must be inserted');
  assert(rootAfterPreciseSync.includes('$ref: ./openapi/registry-only-fixture.yaml#/registryOnlyFixture'));

  const blockedWrite = spawnSync(
    process.execPath,
    [autofillScriptPath, '--write'],
    { cwd: tempRoot, encoding: 'utf8' },
  );
  assert.notEqual(blockedWrite.status, 0, 'write compatibility mode must fail closed on an uncontracted route');
  const blockedWriteReport = JSON.parse(blockedWrite.stdout);
  assert.equal(blockedWriteReport.ok, false);
  assert.equal(blockedWriteReport.blocked, true);
  assert.equal(blockedWriteReport.reason, 'missing_precise_contracts');
  assert.equal(blockedWriteReport.changed, false);
  assert.equal(blockedWriteReport.repository_mutation_performed, false);
  assert.equal(blockedWriteReport.missing_count, 1);
  assert.equal(blockedWriteReport.uncontracted_missing_count, 1);
  assert.equal(blockedWriteReport.missing[0].signature, 'POST /auto-sync-fixture/{id}');
  assert.equal(
    readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8'),
    rootAfterPreciseSync,
    'blocked write mode must leave openapi.yaml byte-identical',
  );
  assert(!rootAfterPreciseSync.includes('TODO document'), 'no generic TODO contract may be synthesized');
  assert(!rootAfterPreciseSync.includes('/auto-sync-fixture/{id}:'), 'uncontracted route must remain absent');

  const blockedCheck = spawnSync(
    process.execPath,
    [autofillScriptPath, '--check'],
    { cwd: tempRoot, encoding: 'utf8' },
  );
  assert.notEqual(blockedCheck.status, 0, 'check mode must fail while an uncontracted runtime route remains');
  const blockedCheckReport = JSON.parse(blockedCheck.stdout);
  assert.equal(blockedCheckReport.reason, 'missing_precise_contracts');
  assert.equal(blockedCheckReport.repository_mutation_performed, false);
  assert.equal(readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8'), rootAfterPreciseSync);

  writeFileSync(join(tempRoot, 'openapi-route-coverage.allowlist.json'), JSON.stringify({
    exact: ['POST /auto-sync-fixture/{id}'],
    prefixes: [],
    files: [],
    required_files: ['routes/exampleRoutes.js'],
  }, null, 2));

  const acceptedWrite = JSON.parse(execFileSync(
    process.execPath,
    [autofillScriptPath, '--write'],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(acceptedWrite.ok, true, 'explicit allowlist ownership should satisfy the coverage gate');
  assert.equal(acceptedWrite.blocked, false);
  assert.equal(acceptedWrite.changed, false);
  assert.equal(acceptedWrite.repository_mutation_performed, false);
  assert.equal(acceptedWrite.missing_count, 0);
  assert.equal(readFileSync(join(tempRoot, 'openapi.yaml'), 'utf8'), rootAfterPreciseSync, 'accepted write mode is still read-only');

  const preciseFinal = JSON.parse(execFileSync(
    process.execPath,
    [preciseSyncPath, '--check'],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(preciseFinal.ok, true, 'precise registry check must pass after composition');
  assert.equal(preciseFinal.missing_count, 0);

  const finalCheck = JSON.parse(execFileSync(
    process.execPath,
    [autofillScriptPath, '--check'],
    { cwd: tempRoot, encoding: 'utf8' },
  ));
  assert.equal(finalCheck.ok, true, 'allowlisted route plus precise refs must satisfy coverage');
  assert.equal(finalCheck.missing_count, 0);
  assert.equal(finalCheck.repository_mutation_performed, false);

  const conflictedRoot = rootAfterPreciseSync.replace(
    '  /registry-only-fixture:\n    $ref: ./openapi/registry-only-fixture.yaml#/registryOnlyFixture',
    '  /registry-only-fixture:\n    post:\n      operationId: conflictingRegistryOnlyFixture\n      responses:\n        "200": { description: conflict }',
  );
  writeFileSync(join(tempRoot, 'openapi.yaml'), conflictedRoot);
  const conflictResult = spawnSync(
    process.execPath,
    [preciseSyncPath, '--check'],
    { cwd: tempRoot, encoding: 'utf8' },
  );
  assert.notEqual(conflictResult.status, 0, 'precise registry sync must fail closed instead of replacing an occupied root path');
  assert.match(conflictResult.stderr, /openapi_precise_contract_path_conflict/);
} finally {
  rmSync(tempRoot, { recursive: true, force: true });
}

console.log('openapi missing-route fail-closed tests passed');
